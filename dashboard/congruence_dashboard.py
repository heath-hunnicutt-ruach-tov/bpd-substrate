#!/usr/bin/env python3
"""congruence_dashboard.py — real-time 0-ULP congruence dashboard for LlamaTov.

Serves a two-axis matrix of per-kernel bit-identity:
  RUNTIME axis  — does the kernel COMPUTE bit-identically to the oracle?
                  (Track A, bit_identical_universal.py)
  MIGRATION axis — does the kernel EMIT byte-identically swipl → swilgt?
                   (Track B, mavhir's emit_diff_matrix.py)

Reads congruence_status.json (produced by Track A -> A2 model, extended per
dashboard/CONGRUENCE_SCHEMA.md). Refreshes on each page load; JSON is
regenerated by gate runs (C3 real-time).

FORWARD-COMPAT RENDER (mavhir 2026-09-02, per Iyun's (b) call):
Renders the versioned schema (CONGRUENCE_SCHEMA.md at dca5d9e / 4d23761)
defensively — every new field uses .get(...) with a graceful "-" fallback,
so this app works with:
  * Old JSON (just `passed` + `kernel`/`shape`/`status`/`max_ulp`/`bit_identical`/`backend`)
  * New JSON with population fields (total_floats/diverged_count/oracle/dtype/device)
  * New JSON with verdict-honest counts (bit_identical/within_tolerance/failed)
  * New JSON with migration axis (migration_source_identical/swipl_sha/swilgt_sha/migration_unit)
  * Any mixture of the above during migration transitions.

If a field is missing, its cell renders "-" and the row is not counted as
present for that axis. THE VERDICT-CLASS RULE is honored: `passed` is never
emitted or consumed as green; only `bit_identical` count is the true 0-ULP
headline. THE EMPTY-POPULATION GUARD is honored: `total_floats` is surfaced;
rows below UNDER_EXERCISED_THRESHOLD are dimmed + marked with a warning.

Usage: python3 congruence_dashboard.py [--port 8477] [--status congruence_status.json]
"""
