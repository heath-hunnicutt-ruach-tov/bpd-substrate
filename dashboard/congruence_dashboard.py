def _fmt_int(n):
    """Human-readable int formatting: 1234567 -> 1,234,567."""
    if n is None:
        return "-"
    try:
        return f"{int(n):,}"
    except (ValueError, TypeError):
        return "-"


def _parse_iso_utc(s):
    """Parse ISO-8601 UTC (e.g. '2026-09-02T14:42:49Z') as a naive datetime in
    UTC. Returns None on any parse failure — freshness stamp then shows
    '(unknown age)' rather than crashing.
    """
    if not s or not isinstance(s, str):
        return None
    # Normalize 'Z' -> '+00:00' so fromisoformat accepts it (pre-3.11 quirk)
    s2 = s.strip()
    if s2.endswith("Z"):
        s2 = s2[:-1] + "+00:00"
    try:
        dt = datetime.datetime.fromisoformat(s2)
        # If tz-aware, convert to UTC + strip tzinfo for compare against utcnow()
        if dt.tzinfo is not None:
            dt = dt.astimezone(datetime.timezone.utc).replace(tzinfo=None)
        return dt
    except (ValueError, TypeError):
        return None


def _freshness(generated_str, threshold_seconds):
    """Compute the freshness stamp for the FRESHNESS STAMP widget.

    Iyun's May-30-recovered pattern via mavchin's archaeology: the dashboard
    must prove its own liveness on its own face. A dashboard that renders a
    stale JSON as if fresh is the same class of failure as the hollow-green
    (looks-current, might-not-be).

    Returns (age_label, css_class):
        age_label: "12s ago", "3m ago", "2h 15m ago", or "(unknown age)"
        css_class: "ok" (< threshold), "warn" (< 3*threshold), "fail" (older)
                   or "muted" if we can't parse the timestamp
    """
    dt = _parse_iso_utc(generated_str)
    if dt is None:
        return "(unknown age)", "muted"
    # utcnow() is deprecated in Python 3.12+; use tz-aware now() then strip
    # for compare with our naive-UTC parsed dt. Backward-compat + no warning.
    now = datetime.datetime.now(datetime.timezone.utc).replace(tzinfo=None)
    delta = now - dt
    seconds = int(delta.total_seconds())
    if seconds < 0:
        # Future timestamp — clock skew or bad data. Show but don't panic.
        return "(from the future, %ds skew)" % (-seconds), "warn"
    if seconds < 60:
        label = "%ds ago" % seconds
    elif seconds < 3600:
        label = "%dm %ds ago" % (seconds // 60, seconds % 60)
    elif seconds < 86400:
        label = "%dh %dm ago" % (seconds // 3600, (seconds % 3600) // 60)
    else:
        label = "%dd %dh ago" % (seconds // 86400, (seconds % 86400) // 3600)
    if seconds <= threshold_seconds:
        cls = "ok"
    elif seconds <= threshold_seconds * 3:
        cls = "warn"
    else:
        cls = "fail"
    return label, cls


def _runtime_verdict(k):
    """Classify a row's RUNTIME axis into (css_class, dot_class, label).

    Honors THE VERDICT-CLASS RULE: only BIT_IDENTICAL is green. PASS_* classes
    are warn (not counted-green). FAIL is fail. Missing/unknown is muted.
    """
    status = k.get("status", "")
    bi = k.get("bit_identical", False)
    if status == "BIT_IDENTICAL" or (bi is True and status == ""):
        return "ok", "ok", status or "BIT_IDENTICAL"
    if status.startswith("PASS"):
        return "warn", "warn", status
    if status == "FAIL" or status.startswith("FAIL"):
        return "fail", "fail", status
    if not status:
        return "muted", "muted", "-"
    # Unknown status class — surface it as warn to catch our attention
    return "warn", "warn", status


def _accuracy_verdict(k):
    """Classify a row's ACCURACY axis (vs TRUTH, per Mavdil c3bbf96 + ebd0cb4).

    accuracy_class field: MATCHED / IMPROVED / INACCURATE / UNMEASURED.
    Returns (css_class, dot_class, label, evidence_html) where evidence_html
    is the mean_abs_err ratio + correctly_rounded delta for IMPROVED/INACCURATE
    rows that carry evidence fields.

    PHYSICS CONSTRAINT (Mavdil's test): BIT_IDENTICAL forces MATCHED. If a
    row claims BIT_IDENTICAL + non-MATCHED accuracy_class, that's a broken
    measurement — render as fail with an explicit "IMPOSSIBLE COMBINATION"
    label so it can't be missed.
    """
    ac = k.get("accuracy_class")
    status = k.get("status", "")
    is_bit_identical = (status == "BIT_IDENTICAL" or k.get("bit_identical") is True)

    if ac is None:
        return "muted", "muted", "-", ""

    # Physics constraint check: BIT_IDENTICAL ENTAILS MATCHED. Any other
    # accuracy_class on a BIT_IDENTICAL row is broken.
    if is_bit_identical and ac != "MATCHED":
        return ("fail", "fail",
                f"IMPOSSIBLE ({ac} on BIT_IDENTICAL)",
                '<span class="fail" style="font-size:.7rem">broken measurement</span>')

    # Evidence rendering: for IMPROVED/INACCURATE, show the ratio + rounded delta
    evidence = ""
    ours = k.get("mean_abs_err_ours")
    stock = k.get("mean_abs_err_stock")
    cr_ours = k.get("correctly_rounded_ours")
    cr_stock = k.get("correctly_rounded_stock")
    if ours is not None and stock is not None and stock > 0:
        ratio = stock / ours
        ratio_str = f"{ratio:.2g}× better" if ratio > 1 else f"{1/ratio:.2g}× worse"
        cr_str = ""
        if cr_ours is not None and cr_stock is not None:
            cr_str = (
                f' · rounded {_fmt_int(cr_ours)}/{_fmt_int(cr_stock)}'
            )
        evidence = (
            f'<span class="muted" style="font-size:.7rem">'
            f'|err| {ours:.2e}/{stock:.2e} ({ratio_str}){cr_str}'
            f'</span>'
        )

    if ac == "MATCHED":
        return "ok", "ok", "MATCHED", evidence
    if ac == "IMPROVED":
        return "improved", "improved", "IMPROVED", evidence
    if ac == "INACCURATE":
        return "fail", "fail", "INACCURATE", evidence
    if ac == "UNMEASURED":
        # Per Mavdil 79ef4702: UNMEASURED must be visually distinct from
        # both INACCURATE (measured-wrong, red) and from muted-absent
        # (no data at all). "We have not checked" is a DIFFERENT FACT
        # from "we checked and are worse." Its own CSS class: amber-
        # outlined empty dot + italic label. Iyun ratified UNMEASURED
        # as its own class precisely to prevent this collapse.
        return "unmeasured", "unmeasured", "UNMEASURED", ""
    # Unknown accuracy_class — surface as warn to catch our attention
    return "warn", "warn", ac, evidence


def _migration_verdict(k):
    """Classify a row's MIGRATION axis. Returns (css_class, dot_class, label).

    Field is `migration_source_identical` (bool). Missing = axis-not-populated-yet
    (renders as muted "-", not a fail). True = byte-identical swipl→swilgt.
    False = source diverged.
    """
    if "migration_source_identical" not in k:
        return "muted", "muted", "-"
    if k["migration_source_identical"] is True:
        return "ok", "ok", "byte-identical"
    if k["migration_source_identical"] is False:
        return "fail", "fail", "DIVERGED"
    return "muted", "muted", "-"


def _under_exercised(k, threshold):
    """Boolean: is this row under the population threshold? Missing total_floats
    = we CAN'T tell, so we don't flag (render but don't dim)."""
    tf = k.get("total_floats")
    if tf is None:
        return False
    try:
        return int(tf) < threshold
    except (ValueError, TypeError):
        return False


